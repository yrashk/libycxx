#!/usr/bin/env python3
"""Extract the draft's library-wide tables for the spec-coverage probes of Part 1 ([library] ..
[utilities]; docs/SPEC_COVERAGE.md).

    tools/spec_audit/part1/draft_tables.py [--html FILE]

reads https://eel.is/c++draft/full (or a saved copy of it) and writes, next to this script,
  data/version.tsv   one line per macro of [version.syn]: name, value, "fs" when the synopsis
                     says freestanding, "hardened" for the macros of /3 that only a hardened
                     implementation defines (else "-"), and the headers it is "also in"
                     (space-separated)
  data/headers.tsv   the headers of Tables 24 and 25 ([headers]) and of Table 27 ([compliance]):
                     header, table ("cpp", "cpp.c", "fs")
The first line of each file records the revision of github.com/Eelis/draft it came from.
Re-run it when the draft changes, then tools/spec_audit/part1/run.py.
"""
import argparse, html, pathlib, re, sys, urllib.request

HERE = pathlib.Path(__file__).resolve().parent
URL = "https://eel.is/c++draft/full"
TAG = re.compile(r"<(?:[^>'\"]|'[^']*'|\"[^\"]*\")*>")


def text(fragment):
    fragment = fragment.replace("'><</span>", "'>&lt;</span>")   # eel.is leaves `<new>`'s < raw
    t = re.sub(r"<(br|/p|/div|/li|/tr|/td|/h[1-6])\b[^>]*>", "\n", fragment)
    t = TAG.sub("", t)
    return html.unescape(t).replace("­", "").replace("​", "")


def section(page, name):
    start = page.index(f"<div id='{name}' class='section'>")
    nxt = page.find("class='section'>", start + 40)
    return page[start:nxt if nxt > 0 else len(page)]


def table(page, label):
    """The cells of the table whose caption carries [tab:label]: each <td>'s text."""
    i = page.index(f"tab:{label}")
    j = page.index("</table>", i)
    return [text(c).strip() for c in re.findall(r"<td[^>]*>(.*?)</td>", page[i:j], re.S)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--html")
    a = ap.parse_args()
    page = (pathlib.Path(a.html).read_text(encoding="utf-8") if a.html
            else urllib.request.urlopen(URL).read().decode("utf-8"))
    rev = re.search(r"github\.com/Eelis/draft/tree/([0-9a-f]{40})", page).group(1)
    head = f"# from https://eel.is/c++draft/full, revision {rev} of github.com/Eelis/draft; generated by draft_tables.py\n"

    lines, hardened = [], False
    for line in text(section(page, "version.syn")).splitlines():
        if "defined in a hardened implementation" in line:
            hardened = True   # /3: the macros that only a hardened implementation defines
        m = re.match(r"\s*#define\s+(__cpp_lib_\w+)\s+(\d+L|see below)\s*(?://(.*))?$", line)
        if not m:
            if lines and line.lstrip().startswith("//"):
                # a comment continued on the next line
                lines[-1][2] += " " + line.strip()
            continue
        lines.append([m.group(1), m.group(2), m.group(3) or "", hardened])
    out = [head]
    for name, value, comment, hard in lines:
        kind = "hardened" if hard else "fs" if re.search(r"\bfreestanding\b", comment) else "-"
        hdrs = re.findall(r"<([\w.]+)>", comment)
        out.append(f"{name}\t{value}\t{kind}\t{' '.join(hdrs)}\n")
    (HERE / "data" / "version.tsv").write_text("".join(out))

    out = [head]
    for label, kind in (("headers.cpp", "cpp"), ("headers.cpp.c", "cpp.c")):
        for cell in table(page, label):
            for h in re.findall(r"<([\w.]+)>", cell):
                out.append(f"{h}\t{kind}\n")
    for cell in table(page, "headers.cpp.fs"):
        for h in re.findall(r"<([\w.]+)>", cell):
            out.append(f"{h}\tfs\n")
    (HERE / "data" / "headers.tsv").write_text("".join(out))
    print(f"{len(lines)} macros, {len(out) - 1} header entries (revision {rev})")


if __name__ == "__main__":
    sys.exit(main())
