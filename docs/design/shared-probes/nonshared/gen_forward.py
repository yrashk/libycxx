#!/usr/bin/env python3
"""Writes, from entry_points.txt, forward.c (the per-image forwarders, hidden, under the names the
compilers call) and export.c (linked into libycxx.so: exports each hidden entry point as
__ycxx_abi_<name>). Probe only: in the design the runtime defines its implementations under the
__ycxx_abi_ names itself, so there is one hop, not two (design §5)."""
import pathlib, sys
here = pathlib.Path(__file__).resolve().parent
out = pathlib.Path(sys.argv[1])
entries = []
for line in (here / "entry_points.txt").read_text().splitlines():
    line = line.split("#")[0].split()
    if line:
        entries.append((line[0], line[1]))
c = ["/* Generated by gen_forward.py: hidden per-image forwarders to libycxx.so's ABI runtime. Every",
     "   entry point takes at most six integer-class arguments, passed through unchanged. */",
     "typedef unsigned long w;"]
for name, kind in entries:
    ret = {"v": "void", "p": "void*", "i": "long", "n": "void"}[kind]
    attrs = "__attribute__((visibility(\"hidden\")))" + (" __attribute__((noreturn))" if kind == "n" else "")
    c.append(f"extern {ret} __ycxx_abi_{name}(w, w, w, w, w, w);")
    body = f"__ycxx_abi_{name}(a, b, c_, d, e, f)"
    if kind in ("p", "i"):
        body = "return " + body
    c.append(f"{attrs} {ret} {name}(w a, w b, w c_, w d, w e, w f) {{ {body}; }}")
(out / "forward.c").write_text("\n".join(c) + "\n")
e = ["/* Generated by gen_forward.py: libycxx.so's exported names for its hidden ABI entry points. */",
     "typedef unsigned long w;"]
for name, kind in entries:
    ret = {"v": "void", "p": "void*", "i": "long", "n": "void"}[kind]
    noret = " __attribute__((noreturn))" if kind == "n" else ""
    e.append(f"extern __attribute__((visibility(\"hidden\"))){noret} {ret} {name}(w, w, w, w, w, w);")
    body = f"{name}(a, b, c_, d, e, f)"
    if kind in ("p", "i"):
        body = "return " + body
    e.append(f"__attribute__((visibility(\"default\"))){noret} {ret} __ycxx_abi_{name}(w a, w b, w c_, w d, w e, w f) {{ {body}; }}")
(out / "export.c").write_text("\n".join(e) + "\n")
